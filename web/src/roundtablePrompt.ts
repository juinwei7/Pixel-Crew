// 圓桌（Roundtable）模式：使用者要的是「直接給我一個討論後的結果」，不是派工、也不是看多個 NPC
// 互相來回辯論。真的開 N 個 agent 多輪辯論會把 token 燒爆（那正是部門派工貴的原因），所以這裡刻意
// 用「單一 NPC 扮演多個角色、一次性內部模擬一場圓桌」的做法：成本 ≈ 一次普通提問，卻仍能產出
// 「各角色意見 + 綜合結論」。輸出直接用 Markdown，讓它在 NPC 的工作日誌裡漂亮呈現，不必額外解析。

import { t } from "./i18n";

export function roundtablePrompt(topic: string): string {
  const trimmed = topic.trim();
  return `${t("你正在 Pixel Crew 主持一場「圓桌討論」。使用者要的是討論後的「結果」，不是過程，也不是要你去派工。")}\n` +
    `${t("重要限制（為了省時省 token）：這是一次性的內部模擬討論。不要呼叫任何工具、不要讀寫檔案、不要動 Git 或設定，")}` +
    `${t("就用你的知識在腦中扮演多個角色辯論一輪，然後直接在這一則回覆內產出結論。")}\n\n` +
    `${t("討論主題：{topic}", { topic: trimmed })}\n\n` +
    `${t("請自己依主題挑 2–4 個最相關的角色上桌（例如工程、QA、產品、設計、營運等），讓他們各自給出簡短意見與理由，")}` +
    `${t("觀點該衝突就衝突；最後你以主持人身分整合出一個明確、可執行的結論。使用者最在意「結論」，所以要具體、能直接照做，不要打太極。")}\n\n` +
    `${t("請完全照以下 Markdown 結構回覆，精簡為主：")}\n` +
    `## 🗣️ ${t("圓桌意見")}\n` +
    `- **${t("角色（立場）")}**：${t("意見與理由")}\n` +
    `${t("（列 2–4 個角色）")}\n\n` +
    `## ✅ ${t("結論")}\n` +
    `${t("一段話講清楚最後怎麼做。")}\n\n` +
    `## ⚠️ ${t("分歧 / 風險")}\n` +
    `- ${t("有就列；沒有就寫「無」")}\n\n` +
    `## ➡️ ${t("下一步")}\n` +
    `- ${t("具體行動")}`;
}
